def add(a, b):
	"""Return the sum of a and b.
	
	Parameters:
	a: the first number
	b: the second number
	"""
	return a + b


def multiply(a, b):
	"""Returns the product of a and b.
	
	Parameters:
	a: the first number to multiply
	b: the second mumber to multiply 
	"""
	return a * b

def is_even(num):
	"""checks if the num is even.
	
	Parameters:
	num: the number to check
	
	Returns: 
	True if num is even, false if num is odd.
	"""
	return num % 2 == 0 

